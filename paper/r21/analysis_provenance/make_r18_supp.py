N_CELLS_MIN, N_CELLS_MAX = 7, 9
cal_sec_max = cal_eps * EP_SPAN / N_CELLS_MIN / PRF_HZ
cal_sec_min = cal_eps * EP_SPAN / N_CELLS_MAX / PRF_HZ
state = M_HIST + DELTA + P_AR

