    ("NA4", "NA-AR(4) (Gaussian)"),
    ("CA16", "Power, CA (white law)"),
    ("OSraw", "Power, OS (white law)"),
    ("D-IN4", "Integration (dwell law)"),
    ("PAMF-H(w)", "PAMF-H, one Doppler (CA law)"),
    ("P-ANMF(bin)", "P-ANMF, one bin (Beta)"),
    ("P-ANMF", "P-ANMF, max (Fisher's $g$)"),
    ("ANMF-SCM(w)", "ANMF-SCM (Kraut--Scharf)"),
    ("ANMF-FP(w)", "ANMF-Tyler (FP law)"),
    ("Clip-OS1", "Clipped, OS scale (Gaussian sim.)"),
